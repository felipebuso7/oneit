export const operationalStatuses = [
  "NEW", "TRIAGE", "AWAITING_SCHEDULING", "SCHEDULED", "ASSIGNED", "TRAVEL_STARTED",
  "ON_SITE", "WORK_STARTED", "IN_PROGRESS", "TECHNICALLY_COMPLETED", "PENDING_CUSTOMER",
  "PENDING_ACCESS", "PENDING_MATERIAL", "PENDING_THIRD_PARTY", "PENDING_CLIENT_IT", "RESCHEDULED",
  "OUT_OF_SCOPE", "CANCELLED", "DUPLICATE", "INVALID", "WAITING_AUTHORIZATION",
] as const;
export type OperationalStatus = (typeof operationalStatuses)[number];

const transitions: Record<OperationalStatus, readonly OperationalStatus[]> = {
  NEW: ["TRIAGE", "DUPLICATE", "INVALID", "CANCELLED"],
  TRIAGE: ["AWAITING_SCHEDULING", "OUT_OF_SCOPE", "PENDING_CUSTOMER", "CANCELLED", "DUPLICATE", "INVALID"],
  AWAITING_SCHEDULING: ["SCHEDULED", "PENDING_MATERIAL", "WAITING_AUTHORIZATION", "CANCELLED"],
  SCHEDULED: ["ASSIGNED", "RESCHEDULED", "CANCELLED"],
  ASSIGNED: ["TRAVEL_STARTED", "RESCHEDULED", "CANCELLED"],
  TRAVEL_STARTED: ["ON_SITE", "PENDING_ACCESS", "RESCHEDULED"],
  ON_SITE: ["WORK_STARTED", "PENDING_ACCESS", "PENDING_CLIENT_IT", "OUT_OF_SCOPE"],
  WORK_STARTED: ["IN_PROGRESS", "PENDING_MATERIAL", "PENDING_CLIENT_IT", "OUT_OF_SCOPE"],
  IN_PROGRESS: ["TECHNICALLY_COMPLETED", "PENDING_CUSTOMER", "PENDING_MATERIAL", "PENDING_THIRD_PARTY", "PENDING_CLIENT_IT", "OUT_OF_SCOPE"],
  TECHNICALLY_COMPLETED: [],
  PENDING_CUSTOMER: ["TRIAGE", "AWAITING_SCHEDULING", "IN_PROGRESS", "CANCELLED"],
  PENDING_ACCESS: ["SCHEDULED", "TRAVEL_STARTED", "ON_SITE", "CANCELLED"],
  PENDING_MATERIAL: ["AWAITING_SCHEDULING", "IN_PROGRESS", "CANCELLED"],
  PENDING_THIRD_PARTY: ["AWAITING_SCHEDULING", "IN_PROGRESS", "CANCELLED"],
  PENDING_CLIENT_IT: ["IN_PROGRESS", "OUT_OF_SCOPE", "CANCELLED"],
  RESCHEDULED: ["SCHEDULED", "CANCELLED"],
  OUT_OF_SCOPE: [], CANCELLED: [], DUPLICATE: [], INVALID: [],
  WAITING_AUTHORIZATION: ["AWAITING_SCHEDULING", "CANCELLED"],
};

export function canTransition(from: OperationalStatus, to: OperationalStatus): boolean {
  return transitions[from].includes(to);
}

export function assertTransition(from: OperationalStatus, to: OperationalStatus): void {
  if (!canTransition(from, to)) throw new Error(`Invalid ticket transition: ${from} -> ${to}`);
}
