import assert from "node:assert/strict";

const base = process.env.PWA_SMOKE_URL ?? "http://localhost:3100";
const manifestResponse = await fetch(`${base}/manifest.webmanifest`);
assert.equal(manifestResponse.status, 200);
const manifest = await manifestResponse.json();
assert.equal(manifest.start_url, "/portal/field");
assert.equal(manifest.display, "standalone");
for (const size of [180, 192, 512]) {
  const response = await fetch(`${base}/pwa/icons/${size}`);
  assert.equal(response.status, 200);
  assert.match(response.headers.get("content-type") ?? "", /image\/png/);
  const png = Buffer.from(await response.arrayBuffer());
  assert.equal(png.subarray(0, 8).toString("hex"), "89504e470d0a1a0a");
  assert.equal(png.readUInt32BE(16), size);
  assert.equal(png.readUInt32BE(20), size);
}
assert.equal((await fetch(`${base}/pwa/icons/123`)).status, 404);
const worker = await fetch(`${base}/sw.js`);
assert.equal(worker.status, 200);
assert.match(worker.headers.get("cache-control") ?? "", /no-store/);
assert.match(worker.headers.get("content-type") ?? "", /javascript/);
assert.equal(worker.headers.get("x-content-type-options"), "nosniff");
const offline = await fetch(`${base}/offline.html`);
assert.equal(offline.status, 200);
const offlineHtml = await offline.text();
assert.match(offlineHtml, /Senha|senha local/);
assert.match(offlineHtml, /rascunhos criptografados/);
const shell = await fetch(`${base}/offline-app.js`);
assert.equal(shell.status, 200);
assert.match(shell.headers.get("content-type") ?? "", /javascript/);
const offlineBundle = await shell.text();
assert.match(offlineBundle, /servicia-execution-draft-v1/);
assert.match(offlineBundle, /\/api\/executions/);
const api = `${base}/api/field-events`;
assert.equal((await fetch(api, { method: "POST", headers: { Origin: "https://untrusted.test", "Content-Type": "application/json" }, body: "{}" })).status, 403);
const headers = { Origin: new URL(base).origin, "Content-Type": "application/json" };
assert.equal((await fetch(api, { method: "POST", headers, body: "invalid-json" })).status, 400);
assert.equal((await fetch(api, { method: "POST", headers, body: "{}" })).status, 400);
assert.equal((await fetch(api, { method: "POST", headers, body: "x".repeat(8193) })).status, 413);
const executionApi = `${base}/api/executions`;
assert.equal((await fetch(executionApi, { method: "POST", headers: { Origin: "https://untrusted.test", "Content-Type": "application/json" }, body: "{}" })).status, 403);
assert.equal((await fetch(executionApi, { method: "POST", headers: { Origin: new URL(base).origin, "Content-Type": "text/plain" }, body: "{}" })).status, 415);
assert.equal((await fetch(executionApi, { method: "POST", headers, body: "invalid-json" })).status, 400);
assert.equal((await fetch(executionApi, { method: "POST", headers, body: "{}" })).status, 400);
assert.equal((await fetch(executionApi, { method: "POST", headers, body: "x".repeat(384 * 1024 + 1) })).status, 413);
const materialApi = `${base}/api/materials`;
assert.equal((await fetch(materialApi, { method: "POST", headers: { Origin: "https://untrusted.test", "Content-Type": "application/json" }, body: "{}" })).status, 403);
assert.equal((await fetch(materialApi, { method: "POST", headers: { Origin: new URL(base).origin, "Content-Type": "text/plain" }, body: "{}" })).status, 415);
assert.equal((await fetch(materialApi, { method: "POST", headers, body: "invalid-json" })).status, 400);
assert.equal((await fetch(materialApi, { method: "POST", headers, body: "{}" })).status, 400);
assert.equal((await fetch(materialApi, { method: "POST", headers, body: "x".repeat(8193) })).status, 413);
console.log("PWA HTTP smoke passed: manifest, PNG dimensions, fallback/bundle, worker headers, icon validation and check-in/execution/material API origin/JSON/size guards.");
